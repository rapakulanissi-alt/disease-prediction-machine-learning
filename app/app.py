import streamlit as st
import pandas as pd
import joblib

# Load trained model
model = joblib.load("models/disease_model.pkl")

# Page settings
st.set_page_config(
    page_title="Disease Prediction System",
    page_icon="🩺",
    layout="centered"
)

# Title
st.title("🩺 Disease Prediction System")
st.write("Select your symptoms and click the Predict button.")

st.warning(
    "This application is an educational machine-learning project "
    "and is not a medical diagnosis."
)

# Symptoms
fever = st.checkbox("Fever")
cough = st.checkbox("Cough")
headache = st.checkbox("Headache")
fatigue = st.checkbox("Fatigue")
sore_throat = st.checkbox("Sore throat")
runny_nose = st.checkbox("Runny nose")
vomiting = st.checkbox("Vomiting")
diarrhea = st.checkbox("Diarrhea")
joint_pain = st.checkbox("Joint pain")

# Predict button
if st.button("🔍 Predict Disease"):

    # Convert True/False into 1/0
    input_data = pd.DataFrame([{
        "fever": int(fever),
        "cough": int(cough),
        "headache": int(headache),
        "fatigue": int(fatigue),
        "sore_throat": int(sore_throat),
        "runny_nose": int(runny_nose),
        "vomiting": int(vomiting),
        "diarrhea": int(diarrhea),
        "joint_pain": int(joint_pain)
    }])

    # Make prediction
    prediction = model.predict(input_data)

    # Display result
    st.success(f"Predicted Disease: {prediction[0]}")

    st.info(
        "The prediction is generated by the trained machine-learning model "
        "using the selected symptoms."
    )
